/** Vagues de l'ordre classique (paires 1-indexées par vague), null si la taille n'a pas de table */
export function classicWaves(size: number): [number, number][][] | null {
  const rows = CLASSIC_ORDERS[size];
  if (!rows) return null;
  return rows.map(row => row.split(' ').map(p => p.split('-').map(Number) as [number, number]));
}

/** Une table classique existe pour cette taille de poule */
export const hasClassicOrder = (size: number): boolean => size in CLASSIC_ORDERS;

/** Ordre classique à plat (paires 1-indexées), null si la taille n'a pas de table */
export function classicMatchOrder(size: number): [number, number][] | null {
  return classicWaves(size)?.flat() ?? null;
}
